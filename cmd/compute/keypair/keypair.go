package keypair

import (
	"github.com/spf13/cobra"

	"jakapil-cli/cmd/compute/client"
)

// NewKeypairCommand returns the parent "compute keypair" command with its
// subcommands: list, show, create and delete.
//
// Note: the Nova keypairs API has no update operation (a keypair is changed by
// deleting it and creating/importing a new one), so there is no "update"
// subcommand.
func NewKeypairCommand() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "keypair",
		Short: "Manage compute keypairs",
		Long:  `Create, list, show and delete OpenStack Nova (compute) SSH keypairs.`,
		Run: func(cmd *cobra.Command, args []string) {
			_ = cmd.Help()
		},
	}

	cmd.AddCommand(
		newListCommand(),
		newShowCommand(),
		newCreateCommand(),
		newDeleteCommand(),
	)

	return cmd
}

func newShowCommand() *cobra.Command {
	return &cobra.Command{
		Use:   "show <keypair-name>",
		Short: "Show a compute keypair",
		Long:  `Show the details of a single compute SSH keypair by its name.`,
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			c, err := client.NewComputeServiceClient(cmd)
			if err != nil {
				return err
			}
			return runShow(cmd, c, args)
		},
	}
}

func newListCommand() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "list",
		Short: "List compute keypairs",
		Long:  `List the SSH keypairs available in the project.`,
		RunE: func(cmd *cobra.Command, args []string) error {
			if allRegions, _ := cmd.Flags().GetBool(client.FlagAllRegions); allRegions {
				return runListAllRegions(cmd)
			}
			c, err := client.NewComputeServiceClient(cmd)
			if err != nil {
				return err
			}
			return runList(cmd, c)
		},
	}
	cmd.Flags().Bool(client.FlagAllRegions, false, "list keypairs in every region the service advertises instead of --region")
	return cmd
}

func newCreateCommand() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "create",
		Short: "Create a compute keypair",
		Long: `Create a new (or import an existing) compute SSH keypair.

The --name flag is required. To import an existing key, pass its public key
with --public-key; otherwise a fresh keypair is generated by the cloud and its
private key is printed once (kept by the service only in public form).`,
		RunE: func(cmd *cobra.Command, args []string) error {
			c, err := client.NewComputeServiceClient(cmd)
			if err != nil {
				return err
			}
			return runCreate(cmd, c)
		},
	}
	cmd.Flags().String("name", "", "keypair name (required)")
	cmd.Flags().String("public-key", "", "existing public key to import (OpenSSH format); omit to generate a new keypair")
	cmd.Flags().String("type", "", "keypair type: ssh or x509 (requires microversion 2.2+)")
	return cmd
}

func newDeleteCommand() *cobra.Command {
	return &cobra.Command{
		Use:     "delete <keypair-name>",
		Short:   "Delete a compute keypair",
		Long:    `Delete a compute SSH keypair by its name.`,
		Aliases: []string{"rm"},
		Args:    cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			c, err := client.NewComputeServiceClient(cmd)
			if err != nil {
				return err
			}
			return runDelete(cmd, c, args)
		},
	}
}
